"""Deterministic IR -> Lean 4 *statement* translator (docs/VERDICT_POLICY.md R-Lean).

R-Lean requires that the theorem's **formulation** (alphabet type, language
definition, the claim itself) is generated by code from the task IR, never by
the LLM -- only the proof *body* is LLM-written. This module is that code.
It never calls an LLM, never raises on malformed input (mirrors
``cfl_system.lib.exponent_pattern``'s "return ``None``, don't guess"
convention), and is a pure function of its input: the same IR always
produces byte-identical Lean text.

Public entry point
-------------------
``render_statement(ir, direction) -> LeanStatement | None``. ``direction`` is
one of the seven literal verdict/pipeline tags the four systems' verdict
gates use: ``"regular"``/``"non_regular"`` (agent_system), ``"cfl"``/
``"non_cfl"`` (cfl_system), ``"dcfl"``/``"non_dcfl"`` (dcfl_system), or
``"ll"`` (ll_system -- LL(k) is never formalized; see below). ``None`` means
"this IR/direction cannot be formalized deterministically"; use
``render_statement_verbose`` to also get the reason.

This module handles the **regular** direction's IR kinds (``grammar``,
``regex``, and a *minimal* subset of ``natural``'s exponent notation -- see
below) plus every piece the other three systems' wrapper modules reuse:
``LeanStatement``, ``alphabet_decl``, ``grammar_decl``, ``parse_regex`` and
``pattern_body`` (the exponent-notation segments/condition -> Lean
converter). ``cfl_system.lib.lean_ir`` and ``dcfl_system.lib.lean_ir`` import
these and add their own directions' predicate and (for cfl) the *full*
exponent-notation parser. They cannot live here: root ``CLAUDE.md``'s
"Import direction" is ``agent_system`` -> nothing, ``cfl_system`` ->
``agent_system``, ``dcfl_system``/``ll_system`` -> both, never the reverse --
so this module cannot import ``cfl_system.lib.exponent_pattern``. Its own
``natural``-kind handling (``_parse_simple_exponent_natural``) is therefore a
small, self-contained subset of that module's grammar (whitespace-separated
``letter^var`` blocks, an optional flat ``| a OP b (and/or ...)*`` condition,
no unions, no arithmetic beyond a bare variable/literal, no multi-letter
units) -- enough for ``agent_system``'s own examples (e.g. ``{a^n b^n | n >=
0}``, reg-01). ``cfl_system.lib.lean_ir`` uses the real, general parser
(``cfl_system.lib.exponent_pattern.parse_exponent_pattern``) for its own
``natural``-kind IRs (unions, richer arithmetic, multi-letter units), feeding
its result into this module's ``pattern_body`` -- so the segments/condition
-> Lean *conversion* logic itself is never duplicated, only the small text
parser is (mirrors the existing precedent of ``dcfl_system.lib.dpda`` keeping
its own field-name convention rather than importing ``cfl_system``'s).

Alphabet type
-------------
``inductive Letter | a | b | c ... deriving DecidableEq, Repr`` -- one named
constructor per letter of ``ir.alphabet`` (or ``language_spec``'s
``terminals``/``alphabet`` field, per IR kind), rather than ``Fin k``.
Reasoning: every generated word literal and grammar rule reads as
``Letter.a``/``Letter.b`` instead of an opaque ``(0 : Fin k)``/``(1 : Fin k)``,
which matters because this text is read by both the LLM formalizer (writing
the proof body against these exact names) and a human auditing a `verified`
result. ``Fin k`` would need the same "letter -> index" bookkeeping duplicated
by every reader; a named inductive puts it in one place (this module) and
erases it from everything downstream. Named ``Letter``, not ``Sym``: Mathlib
already has a top-level ``def Sym (α : Type*) (n : ℕ) := ...`` (symmetric
powers, ``Mathlib.Data.Sym.Basic``, transitively imported by every direction
here) -- ``inductive Sym`` in ``check.lean`` collides with it
("`Sym` has already been declared"), confirmed against the pinned image
(``docker run tfl-lean4``) while writing this module.

``deriving DecidableEq, Repr`` only, **not** ``Fintype``, on the ``Letter``
inductive itself: ``deriving Fintype`` for a plain enum inductive fails to
elaborate under the pinned toolchain, ``leanprover/lean4:v4.33.0``
(confirmed with a minimal ``inductive Letter | a | b deriving Fintype``
against ``docker run tfl-lean4``: `` Tactic `rewrite` failed... Application
type mismatch: ... Letter.enumList_nodup ... expected ...
(↑Letter.enumList).Nodup`` -- a `Finset`/`Multiset` coercion mismatch
inside the derive handler itself, not anything to do with this module's
generated names -- and the hint Lean prints for the error,
``deriving instance Fintype for Letter`` as a separate command, hits the
exact same broken handler). Every ``LeanStatement`` this module or its
``cfl_system``/``dcfl_system`` wrappers ever produced with ``Fintype`` in
the ``deriving`` clause would have failed to type-check regardless of the
proof body.

Whether a ``Fintype Letter`` instance is needed at all depends on the
direction: ``Language.IsRegular``/``Language.IsContextFree``
(``Mathlib.Computability.{DFA, ContextFreeGrammar}``) quantify ``Fintype``
over the automaton's *state* type only, never over the alphabet -- REG/CFL
statements need nothing beyond ``DecidableEq Letter``. langlib's
``is_DCF``/``is_DPDA`` (``Langlib/Automata/DeterministicPushdown/
Definition.lean``: ``is_DPDA {T : Type} [Fintype T] (L : Language T) :
Prop``) is the opposite: it takes ``[Fintype T]`` on the alphabet as an
explicit instance argument, so a DCFL statement genuinely cannot elaborate
without one (confirmed: ``dcfl_system.lib.lean_ir``'s statements fail
``failed to synthesize instance ... Fintype Letter`` against ``docker run
tfl-lean4`` without it). ``fintype_instance_decl(sym_map)`` is the
workaround: a literal ``Finset`` of every constructor plus a ``decide``d
completeness proof (``instance : Fintype Letter where elems := {Letter.a,
...}; complete := by intro x; cases x <;> decide``), which *does* compile
-- ``dcfl_system.lib.lean_ir`` appends it after ``alphabet_decl`` for both
its directions; ``agent_system.lib.lean_ir``/``cfl_system.lib.lean_ir``
never call it, since REG/CFL statements don't need it and it would just be
dead code in their generated files.

CFL/DCFL predicate provenance
------------------------------
Checked directly against the pinned toolchain (``agent_system/docker/tfl_lean``,
``leanprover/lean4:v4.33.0`` + Mathlib, ``lake exe cache get`` already warms
the *whole* Mathlib .olean cache, confirmed via ``docker run tfl-lean4`` while
writing this module) and against a read-only reference clone of ``langlib``
(commit ``c5fb8340b42543713f79e1c283a3f6a929cb71ef``, ``lean-toolchain``
v4.33.0) kept outside the repo for the duration of this work -- it is
reference-only, never imported at runtime and not wired into any test's
lookup path; grep it directly (``Langlib/Classes/...``) when re-checking a
predicate/lemma name below:

- **REG**: Mathlib's own ``Language.IsRegular`` (``Mathlib.Computability.Language``,
  transitively available once ``Mathlib.Computability.RegularExpressions``
  is imported, which ``TflLean`` already does) -- langlib's own regularity
  class (``is_RG``, ``Langlib/Grammars/RightRegular/Definition.lean``) is a
  *different*, grammar-shaped definition its examples don't actually use for
  proofs (``Langlib/Classes/Regular/Examples/AnBn.lean`` proves
  ``anbn_not_isRegular : ¬ anbn.IsRegular`` directly against Mathlib's
  predicate via ``Language.isRegular_iff_finite_range_leftQuotient``).
- **CFL**: Mathlib's own ``Language.IsContextFree`` (``∃ g : ContextFreeGrammar
  T, g.language = L`` -- ``Mathlib.Computability.ContextFreeGrammar``), *not*
  langlib's own ``is_CF`` (``Langlib/Classes/ContextFree/Definition.lean``,
  built over langlib's separate unrestricted-``grammar`` type). The two are
  proved equivalent by langlib itself (``is_CF_iff_isContextFree``), and
  critically langlib proves its pumping lemma and Ogden's lemma **directly
  in Mathlib's own namespace**: ``Language.IsContextFree.pumping``
  (``Langlib/Classes/ContextFree/Pumping/Pumping.lean``) and
  ``Language.IsContextFree.ogdens_lemma``
  (``Langlib/Classes/ContextFree/Basics/Ogden.lean``) -- so
  ``Language.IsContextFree`` is "the one with the pumping lemma" the task
  asked to identify, while also being the Mathlib-native predicate that only
  needs ``import Mathlib.Computability.ContextFreeGrammar`` to *state* (no
  langlib dependency for the statement itself, only for a ``non_cfl`` proof
  body that cites the pumping/Ogden lemmas).
- **DCFL**: Mathlib has no deterministic-pushdown-automaton formalization at
  all (``grep``ped ``Mathlib/Computability/`` while writing this module: no
  hit), so the DCFL direction uses langlib's own ``is_DCF``
  (``Langlib/Classes/DeterministicContextFree/Definition.lean``:
  ``is_DCF (L : Language T) : Prop := is_DPDA L``, over langlib's own DPDA
  automaton type) -- there is no alternative.
- **langlib availability**: ``agent_system/docker/tfl_lean/lakefile.toml``
  now pins ``langlib`` as a Lake dependency (``rev
  c5fb8340b42543713f79e1c283a3f6a929cb71ef``, matching the reference clone
  above) and the pinned ``tfl-lean4`` image has it built in
  (``docker run tfl-lean4 ls .lake/packages/`` lists ``langlib`` alongside
  ``mathlib``, confirmed while writing this module) -- so, as of this
  module, statements for every direction (including ``cfl``/``non_cfl``/
  ``dcfl``/``non_dcfl`` with their real ``Langlib.Classes...`` imports, not
  a stripped-imports substitute) actually type-check against the current
  image; ``cfl_system.lib.lean_ir``'s and ``dcfl_system.lib.lean_ir``'s own
  Docker-conditional tests exercise this directly.

LL(k)
-----
Always ``None`` (``direction == "ll"``): LL(k)-ness is a property of a
*grammar*'s parsing algorithm, not of the language it generates, so "is this
language LL(k)" isn't even a well-formed Mathlib/langlib statement the way
regularity/CFL-ness/DCFL-ness are (see docs/VERDICT_POLICY.md R-Lean: "LL(k)
— не формализуется").

Language construction
----------------------
- ``grammar`` kind -> Mathlib ``ContextFreeGrammar Letter`` (``g``) with
  ``L := g.language`` (used for all three of reg/cfl/dcfl -- e.g. dcfl's
  exam_04, ``task_grammar_aSSb``, is a grammar IR).
- ``regex`` kind (``has_backreferences: false`` only -- ``true`` means the
  pattern isn't a regular expression at all and is rejected with a reason)
  -> Mathlib ``RegularExpression Letter`` (``re``) with ``L := re.matches'``.
  Supports literal alphabet characters, ``|`` (union), implicit
  concatenation, ``*``/``+``/``?`` (postfix repetition/optional) and ``()``
  grouping -- i.e. plain regular-expression syntax, nothing POSIX-specific
  (no character classes, no anchors, no backreferences).
- ``natural`` kind with exponent notation -- ``{a^n b^n c^m | ...}`` style --
  via ``List.replicate``/(for multi-letter units) ``List.replicate ... .flatten``
  segments existentially quantified over ℕ, `w = <segments>`` conjoined with
  the (optional) condition. A word this shape describes needn't be
  "resolvable" the way ``cfl_system.lib.exponent_pattern``'s runtime *oracle*
  needs to be (see that module's docstring) -- a Lean ``Prop`` is just an
  existentially-quantified equation, not an algorithm, so this module
  supports strictly more IR than that module's ``accepts()`` can decide.
  What it does *not* support: ``-`` (unbounded ℕ subtraction would silently
  change the meaning) anywhere in an exponent expression.
- ``natural`` kind describing a palindrome (``w = reverse(w)`` / ``w = w^R`` /
  ``w = wᴿ``, case-insensitively) -> ``L := {w : List Letter | w = w.reverse}``.
- Anything else (``predicate``, ``arithmetic_index``, cfl's
  ``grammar_filter``/``repeated_subword``/``exists_decomposition``, a
  ``natural`` description that is neither exponent notation nor a simple
  palindrome, a dcfl ``set_builder`` that isn't the letter-domain shape
  ``cfl_system/lib/lean_ir.py`` and ``dcfl_system/lib/lean_ir.py`` handle) ->
  ``None`` with a reason. This module never invents a formalization for
  something it cannot mechanically translate.
"""

