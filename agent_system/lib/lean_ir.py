@dataclass(frozen=True)
class LeanStatement:
    """A deterministically-generated Lean 4 theorem formulation.

    ``alphabet_decl``: the ``inductive Letter ...`` declaration.
    ``language_decl``: whatever else the statement needs (grammar/regex/`NT`
      declarations and ``def L : Language Letter := ...``).
    ``theorem_decl``: ``"theorem tfl_main : <Prop>"`` -- no ``:= by ...``;
      :meth:`render` appends that with the harness-supplied proof body.
    ``imports``: full ``import ...`` lines, in the order they should appear,
      always starting with ``"import TflLean"``.
    ``name``: the theorem's name (``"tfl_main"`` -- R-Lean's fixed contract).
    """

    alphabet_decl: str
    language_decl: str
    theorem_decl: str
    imports: list[str] = field(default_factory=list)
    name: str = "tfl_main"

    def render(self, proof: str = "sorry") -> str:
        """Assemble the full ``.lean`` file text, substituting *proof* into
        the ``:= by`` block. The harness substitutes the formalizer LLM's
        proof body here; the default ``"sorry"`` is what the Docker-conditional
        syntax-only test in ``agent_system/tests/test_lean_ir.py`` compiles."""
        parts = list(self.imports)
        parts.append("")
        parts.append(self.alphabet_decl)
        parts.append("")
        parts.append(self.language_decl)
        parts.append("")
        parts.append(f"{self.theorem_decl} := by\n  {proof}")
        return "\n".join(parts) + "\n"


